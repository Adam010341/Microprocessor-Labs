#!/usr/bin/env python3
"""Generate count_primes.S (pic-as, PIC18F4520).

The routine is mostly straight-line code (one block per sieving prime, an
unrolled count of one segment), so it is written out by this script instead
of by hand. Run it from anywhere:

    python3 tools/gen_count_primes.py > count_primes.S

Algorithm (see HANDOFF.md for the long version):
  * Only odd numbers are sieved. Global index g <-> value 2g+1.
  * Segment K holds g = 255K .. 255K+254 in arr positions 1..255
    (arr is the whole of bank 1, so it starts on a 256-byte boundary and
    FSR2L wraps from 255 to 0 exactly at the end of a segment).
  * 255 = 3*5*17, so multiples of 3, 5 and 17 sit at the same positions in
    every segment. They are set to 0xFF once per call and never touched
    again; the count only looks at the other 128 positions.
  * Every other prime p (7..251) keeps the index of its next multiple in
    nxt[]. Marking a segment is "setf INDF2 / addwf FSR2L / bnc" and the
    FSR2L value left after the wrap is the index of the next multiple in the
    next segment, so nothing is recomputed between segments.
"""

def primes_upto(n):
    return [p for p in range(2, n + 1) if all(p % d for d in range(2, int(p ** 0.5) + 1))]

SEG = 255
PRE = (3, 5, 17)                       # handled by the fixed pattern
MARK = [p for p in primes_upto(251) if p > 2 and p not in PRE]
assert len(MARK) == 50


def is_pattern(i):                     # i = index inside a segment
    return i % 3 == 1 or i % 5 == 2 or i % 17 == 8


CAND = [i for i in range(SEG) if not is_pattern(i)]
assert len(CAND) == 128


def unroll(p):
    if p < 16:
        return 8
    if p < 48:
        return 4
    return 2


out = []
emit = out.append


def ins(op, args="", comment=""):
    line = "    %-7s %s" % (op, args) if args else "    %s" % op
    if comment:
        line = "%-40s; %s" % (line, comment)
    emit(line.rstrip())


def label(name, comment=""):
    emit("%s:%s" % (name, ("   ; " + comment) if comment else ""))


HEADER = r"""; count_primes.S  --  PIC18F4520, pic-as (XC8 v4.00)
;
;   extern unsigned int count_primes(unsigned int n, unsigned int m);
;   returns the number of primes p with n <= p <= m
;
; GENERATED by tools/gen_count_primes.py -- edit the generator, not this file.
;
; Segmented sieve over odd numbers only:
;   global index g  <->  odd value 2g+1
;   segment K       =    g in [255K, 255K+254], stored in arr positions 1..255
;   arr             =    all 256 bytes of bank 1, so it is 256-byte aligned and
;                        FSR2L wraps 255 -> 0 exactly at the end of a segment
;   entry value     =    0x00 maybe prime, 0xFF composite
; 255 = 3*5*17, so the multiples of 3, 5 and 17 are at fixed positions in every
; segment: they are set to 0xFF once and the count skips them. The other 50
; primes (7..251) remember the index of their next multiple in nxt[], so a new
; segment does not recompute any starting point. 2, 3, 5 and 17 themselves are
; added separately at the start.
;
; Judge rules: every file-register operand states its RAM access bit (", a"
; for access RAM/SFRs, ", b" with BANKSEL for arr/nxt); no fixed RAM addresses;
; all state is reset at the start of every call (it is called 20 times in one
; run); BSR is not 0 on entry, so it is saved and restored.

#include "xc.inc"
GLOBAL _count_primes
EXTRN _count_primes$0, _count_primes$1

PSECT udata_acs
cp_nL:   DS 1        ; n (clamped to >= 2)
cp_nH:   DS 1
cp_mL:   DS 1        ; m
cp_mH:   DS 1
cp_cL:   DS 1        ; prime count
cp_cH:   DS 1
cp_gL:   DS 1        ; scratch: g_n / g_m
cp_gH:   DS 1
cp_K:    DS 1        ; current segment
cp_K0:   DS 1        ; first segment (contains n)
cp_Km:   DS 1        ; last segment (contains m)
cp_a:    DS 1        ; index of the first odd >= n inside segment K0
cp_b:    DS 1        ; index of the last odd <= m inside segment Km
cp_t1:   DS 1        ; scratch
cp_t2:   DS 1        ; scratch
cp_bsr:  DS 1        ; caller's BSR

PSECT udata_bank1
arr:     DS 256      ; one segment; must be exactly one whole bank (see above)

PSECT udata_bank2
nxt:     DS 50       ; per sieving prime: index of its next multiple in the
                     ; current segment (written before it is ever read)

PSECT mytext, local, class=CODE, reloc=2
"""

emit(HEADER.rstrip("\n"))

# ----------------------------------------------------------------- helpers
# Written out inline (no assembler macros), so nothing depends on pic-as macro
# syntax.

def div255(q, r, tag):
    """q:r = g div/mod 255 for the 15-bit g in cp_gH:cp_gL.
    256*gH + gL = 255*gH + (gH+gL) and gH+gL <= 382: one correction at most."""
    return """    movf    cp_gH, w, a
    addwf   cp_gL, w, a                 ; W = (gH+gL) & 0FFh, C = (gH+gL) >= 256
    movwf   %(r)s, a
    movff   cp_gH, %(q)s%(pad)s; movff leaves STATUS alone
    bc      %(t)s_adj
    incf    %(r)s, w, a%(pad2)s; Z = (r == 255)
    bnz     %(t)s_ok
%(t)s_adj:
    incf    %(r)s, f, a%(pad2)s; r = gH+gL-255
    incf    %(q)s, f, a
%(t)s_ok:""" % dict(q=q, r=r, t=tag, pad=" " * (21 - len(q)), pad2=" " * (22 - len(r)))


def smallp(q):
    """count += 1 if n <= q <= m   (q < 256; here n >= 2, m >= n, nH == 0)"""
    return """    movf    cp_nL, w, a
    sublw   %(q)-28d; C = (%(q)d >= nL)
    bnc     cp_sp%(q)d_no
    movf    cp_mH, w, a
    bnz     cp_sp%(q)d_yes
    movlw   %(q)d
    subwf   cp_mL, w, a                 ; C = (mL >= %(q)d)
    bnc     cp_sp%(q)d_no
cp_sp%(q)d_yes:
    incf    cp_cL, f, a
cp_sp%(q)d_no:""" % dict(q=q)


# ----------------------------------------------------------------- entry
emit(r"""
_count_primes:
    movff   BSR, cp_bsr
    movff   _count_primes$0, cp_nL
    movff   (_count_primes$0+1), cp_nH
    movff   _count_primes$1, cp_mL
    movff   (_count_primes$1+1), cp_mH
    clrf    cp_cL, a
    clrf    cp_cH, a
    ; n < 2  ->  n = 2   (0 and 1 are not prime)
    movf    cp_nH, w, a
    bnz     cp_n_ok
    movlw   2
    cpfslt  cp_nL, a                    ; skip if nL < 2
    bra     cp_n_ok
    movwf   cp_nL, a
cp_n_ok:
    ; m < n  ->  0
    movf    cp_nL, w, a
    subwf   cp_mL, w, a
    movf    cp_nH, w, a
    subwfb  cp_mH, w, a                 ; C = (m >= n)
    bc      cp_m_ok
    goto    cp_finish
cp_m_ok:
    ; 2, 3, 5, 17 are not found by the sieve: add them here
    movf    cp_nH, w, a
    bnz     cp_small_done
%(small)s
cp_small_done:
    ; g_m = (m-1) >> 1  : index of the last odd <= m
    movlw   1
    subwf   cp_mL, w, a
    movwf   cp_gL, a
    movlw   0
    subwfb  cp_mH, w, a
    movwf   cp_gH, a
    bcf     STATUS, 0, a
    rrcf    cp_gH, f, a
    rrcf    cp_gL, f, a
%(divm)s
    ; g_n = n >> 1      : index of the first odd >= n (n >= 2, so it is >= 3)
    movf    cp_gL, w, a                 ; keep g_m in t1:t2 for the compare
    movwf   cp_t1, a
    movf    cp_gH, w, a
    movwf   cp_t2, a
    bcf     STATUS, 0, a
    rrcf    cp_nH, w, a
    movwf   cp_gH, a
    rrcf    cp_nL, w, a
    movwf   cp_gL, a
    ; no odd number in [n, m]  ->  only the small primes above
    subwf   cp_t1, w, a
    movf    cp_gH, w, a
    subwfb  cp_t2, w, a                 ; C = (g_m >= g_n)
    bc      cp_have_odd
    goto    cp_finish
cp_have_odd:
%(divn)s
    ; arr positions 1..255 <- the 3/5/17 pattern (0FFh) or 0
    lfsr    0, arr+1""" % dict(
    small="\n".join(smallp(q) for q in (2, 3, 5, 17)),
    divm=div255("cp_Km", "cp_b", "cp_dm"),
    divn=div255("cp_K0", "cp_a", "cp_dn")))

for i in range(SEG):
    ins("setf" if is_pattern(i) else "clrf", "POSTINC0, a")

emit(r"""    ; if the first segment is not also the last, mark positions 1..a as
    ; composite so the full-segment count does not see numbers below n
    movf    cp_K0, w, a
    cpfseq  cp_Km, a
    bra     cp_premark
    bra     cp_premark_done
cp_premark:
    movf    cp_a, w, a
    bz      cp_premark_done
    movwf   cp_t1, a
    lfsr    0, arr+1
cp_premark_loop:
    setf    POSTINC0, a
    decfsz  cp_t1, f, a
    bra     cp_premark_loop
cp_premark_done:
    movff   cp_K0, cp_K
    lfsr    2, arr                      ; FSR2H stays on arr, FSR2L walks it
    BANKSEL(nxt)                        ; BSR = bank of nxt[] while sieving
    goto    st_%d

cp_finish:
    movff   cp_cL, _count_primes$0
    movff   cp_cH, (_count_primes$0+1)
    movff   cp_bsr, BSR
    return
""" % MARK[0])

# ----------------------------------------------------------------- stages
emit(r"""; ---------------------------------------------------------------------------
; Stage loop. At st_p the primes below p are active. st_p checks whether p
; becomes active in segment K:
;   K <  Kp : no                      -> sieve this segment (run_p)
;   K == Kp : p*p is in this segment  -> first multiple is p*p (if p*p <= m)
;   K >  Kp : only possible in the first segment K0; the first odd multiple
;             at or after index 255*K0 is computed once with the multiplier.
; Then it falls through to the next prime's check. run_p sieves one segment
; with the active primes, counts it and goes back to st_p.
;
; Modular start, for c = 255 mod p, F = ceil(c*65536/p):
;   q = floor(K0*c/p) = high byte of (K0*F_hi + hi(K0*F_lo))   (exact, K0<=128)
;   r = K0*c - q*p = (255*K0) mod p      (fits in 8 bits, so low bytes only)
;   o = (h - r) mod p, h = (p-1)/2       (2(255*K0+o)+1 is a multiple of p)
; ---------------------------------------------------------------------------""")

prev = None
for j, p in enumerate(MARK):
    p2 = p * p
    gp2 = (p2 - 1) // 2
    Kp, idx2 = divmod(gp2, SEG)
    c = 255 % p
    F = -(-c * 65536 // p)
    FL, FH = F & 0xFF, F >> 8
    h = (p - 1) // 2
    emit("")
    label("run_%d" % p, "primes < %d active" % p)
    if prev is not None:
        ins("call", "blk_%d" % prev)
    ins("call", "seg_end")
    ins("btfsc", "STATUS, 0, a", "C = 1: last segment done")
    ins("goto", "cp_finish")
    label("st_%d" % p, "p=%d  p*p=%d  Kp=%d  index %d" % (p, p2, Kp, idx2))
    ins("movlw", str(Kp))
    ins("subwf", "cp_K, w, a")
    ins("bnc", "run_%d" % p, "K < Kp")
    ins("bnz", "md_%d" % p, "K > Kp")
    ins("movlw", str(p2 & 0xFF))
    ins("subwf", "cp_mL, w, a")
    ins("movlw", str(p2 >> 8))
    ins("subwfb", "cp_mH, w, a", "C = (m >= p*p)")
    ins("bnc", "run_%d" % p, "p*p > m: never needed")
    ins("movlw", str(idx2))
    ins("bra", "sv_%d" % p)
    label("md_%d" % p)
    ins("movlw", str(c), "c = 255 mod p")
    ins("mulwf", "cp_K, a")
    ins("movff", "PRODL, cp_t1")
    ins("movlw", str(FL), "F = %d" % F)
    ins("mulwf", "cp_K, a")
    ins("movff", "PRODH, cp_t2")
    ins("movlw", str(FH))
    ins("mulwf", "cp_K, a")
    ins("movf", "cp_t2, w, a")
    ins("addwf", "PRODL, w, a")
    ins("movlw", "0")
    ins("addwfc", "PRODH, w, a", "W = q")
    ins("movwf", "cp_t2, a")
    ins("movlw", str(p))
    ins("mulwf", "cp_t2, a")
    ins("movf", "PRODL, w, a")
    ins("subwf", "cp_t1, w, a", "W = r")
    ins("sublw", str(h), "W = h - r")
    ins("bc", "sv_%d" % p)
    ins("addlw", str(p))
    label("sv_%d" % p)
    ins("movwf", "BANKMASK(nxt+%d), b" % j)
    nxt_st = "st_%d" % MARK[j + 1] if j + 1 < len(MARK) else "st_all"
    ins("bra", nxt_st)
    prev = p

emit("")
label("run_all", "all 50 primes active")
ins("call", "blk_%d" % MARK[-1])
ins("call", "seg_end")
ins("btfsc", "STATUS, 0, a")
ins("goto", "cp_finish")
label("st_all")
ins("bra", "run_all")

# ----------------------------------------------------------------- marking
emit(r"""
; ---------------------------------------------------------------------------
; Marking chain, largest prime first. "call blk_p" marks this segment with
; every prime <= p and returns. FSR2H = high(arr) throughout; FSR2L = position.
; position = index + 1, and when FSR2L wraps the value left in it is the index
; of the next multiple in the next segment, which goes back into nxt[].
; ---------------------------------------------------------------------------""")
for j in range(len(MARK) - 1, -1, -1):
    p = MARK[j]
    U = unroll(p)
    emit("")
    label("blk_%d" % p)
    ins("incf", "BANKMASK(nxt+%d), w, b" % j)
    ins("movwf", "FSR2L, a")
    ins("movlw", str(p))
    label("mk_%d" % p)
    for u in range(U):
        ins("setf", "INDF2, a")
        ins("addwf", "FSR2L, f, a")
        if u < U - 1:
            ins("bc", "mx_%d" % p)
        else:
            ins("bnc", "mk_%d" % p)
    label("mx_%d" % p)
    ins("movf", "FSR2L, w, a")
    ins("movwf", "BANKMASK(nxt+%d), b" % j)
ins("return")

# ----------------------------------------------------------------- counting
emit(r"""
; ---------------------------------------------------------------------------
; seg_end: count the primes of segment K and move to K+1.
; Returns C = 1 when K was the last segment.
; Entries are 00h or FFh, so their 8-bit sum is -(number of composites).
; ---------------------------------------------------------------------------
seg_end:
    movf    cp_K, w, a
    cpfseq  cp_Km, a
    bra     seg_full
    ; last segment: count positions a'+1 .. b+1, a' = (K == K0) ? a : 0
    cpfseq  cp_K0, a                    ; W = K
    bra     seg_a0
    movf    cp_a, w, a
    bra     seg_a_set
seg_a0:
    movlw   0
seg_a_set:
    movwf   cp_t1, a                    ; t1 = a'
    lfsr    0, arr
    incf    cp_t1, w, a
    movwf   FSR0L, a                    ; FSR0 -> position a'+1
    movf    cp_t1, w, a
    subwf   cp_b, w, a
    addlw   1
    movwf   cp_t1, a                    ; t1 = len = b - a' + 1  (1..255)
    movwf   cp_t2, a                    ; t2 = loop counter
    movlw   0
seg_last_loop:
    addwf   POSTINC0, w, a
    decfsz  cp_t2, f, a
    bra     seg_last_loop
    addwf   cp_t1, w, a                 ; W = len - composites
    addwf   cp_cL, f, a
    btfsc   STATUS, 0, a
    incf    cp_cH, f, a
    bsf     STATUS, 0, a                ; done
    return

seg_full:
    BANKSEL(arr)
    movlw   0""".rstrip("\n"))
for i in CAND:
    ins("addwf", "BANKMASK(arr+%d), w, b" % (i + 1))
    ins("clrf", "BANKMASK(arr+%d), b" % (i + 1))
emit(r"""    addlw   128                         ; W = 128 - composites
    addwf   cp_cL, f, a
    btfsc   STATUS, 0, a
    incf    cp_cH, f, a
    incf    cp_K, f, a
    BANKSEL(nxt)
    bcf     STATUS, 0, a                ; not done
    return""")

print("\n".join(out))
