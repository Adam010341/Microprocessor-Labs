MAIN:
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;initializing FSR
    LFSR 0, 0x101; FSR0=left
    LFSR 1, 0x0FF; FSR1=right
    LFSR 2, 0x300; FSR2=stack pointer
    movf 0x00,w; WREG=length
    addwf FSR1L;FSR1=right
    bnc no_carry
    INCF FSR1H;
    no_carry:
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    ;initialize stack
    movf FSR0L,w; left lower address to WREG
    movwf POSTINC2; stack push left
    movf FSR1L, w; right lower address to WREG
    movwf INDF2; stack push right
    ;stack pointer points to the top element
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    loop:
    
    ;check if stack is empty
    movf FSR2L, w;
    sublw 0x2FF;
    BZ terminate;
    
    ;set right pointer
    movf POSTDEC2, w;
    movwf FSR1L; right= WREG
    movff FSR1L, 0x03;0x03=right (fixed)
    
    ;set left pointer
    movf POSTDEC2, w;
    movwf FSR0L; left= WREG
    movff FSR0L, 0x02;0x02=left (fixed)
    
    ;set pivot position
    addlw 0xFF; WREG=WREG-1
    movwf 0x04; 0x00=pivot position
    movwf FSR0L;
    movff POSTINC0, 0x01 ; 0x01 = pivot value
    
    GOTO findLeft
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    findLeft:
    movf 0x01,w
    cpfsgt POSTINC0       ; skip if A[i] > pivot
    GOTO leftBound      
    decf FSR0L
    GOTO findRight     
    leftBound:  
    movf 0x03,w 
    cpfsgt FSR0L 
    GOTO findLeft 
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    findRight:
    movf POSTDEC1,w;move pivot to WREG
    subwf 0x01,w
    BNC findRight
    
    movf PREINC1, w 
    movf FSR0L, W; move left to WREG
    cpfsgt FSR1L; skip if right > left
    GOTO buildStackLeft;
    GOTO swap; 
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    swap:
    movf INDF0, w; move left to WREG
    movff INDF1, INDF0;mvof right to left
    movwf INDF1;move WREG to right
    GOTO findLeft
    ;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
    buildStackLeft:
    movf INDF1, w         ; W = A[j]
    movff 0x01, INDF1     ; A[j] = pivot
    movff 0x04, FSR0L    
    movwf INDF0           
    ;push left part: [pivot .. j-1], push if j > left (at least 2 elements)
    movf 0x02, w; W = left
    cpfsgt FSR1L; skip if j > left
    GOTO buildStackRight
    movff 0x02, PREINC2 ; stack push left
    decf FSR1L;  FSR1L = j-1
    movff FSR1L, PREINC2  ; stack push right = j-1
    incf FSR1L ; FSR1L = j

    buildStackRight:
    ;push right part: [j+1 .. hi], push if j+1 < hi (at least 2 elements)
    incf FSR1L; FSR1L = j+1 (pivot of right part)
    movf 0x03, w ; W = hi
    cpfslt FSR1L; skip if j+1 < hi
    GOTO loop
    incf FSR1L; FSR1L = j+2 = left of right part
    movff FSR1L, PREINC2  ; stack push left
    movff 0x03, PREINC2   ; stack push right

